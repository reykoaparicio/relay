import { z } from 'zod';
import { costSummarySchema } from '../domain/ledger.js';
import { idSchema } from '../ids.js';
import { microusdSchema } from '../money.js';
import { epochMsSchema, sha256Schema, stepKeySchema } from '../primitives.js';
import { APPROVAL_STALE_REASONS } from '../errors.js';
import {
  approvalDecisionSchema,
  costCertaintySchema,
  providerIdSchema,
  stepStateSchema,
  terminalRunStatusSchema,
} from '../status.js';
import { reviewOutcomeSchema } from './review.v1.js';

/** A stored report generated before decision 1 has no `totals.hasEstimates`: derived from `settledEstimated`. */
function withHasEstimates(v: unknown): unknown {
  if (typeof v !== 'object' || v === null || 'hasEstimates' in v) return v;
  const est = (v as { settledEstimated?: unknown }).settledEstimated;
  return { ...v, hasEstimates: typeof est === 'number' && est > 0 };
}

/** Report totals: {@link costSummarySchema}, tolerating reports stored before `hasEstimates` existed. */
const reportTotalsSchema = z.preprocess(withHasEstimates, costSummarySchema);

/**
 * `report.v1`: generated by the engine on every terminal transition (06 F17); never requested from a model,
 * so it may use contracts ids and enums.
 */
export const reportV1Schema = z.object({
  schemaId: z.literal('report.v1'),
  runId: idSchema('run'),
  projectId: idSchema('project'),
  goal: z.string(),
  status: terminalRunStatusSchema,
  verdict: reviewOutcomeSchema.nullable(), // latest review.v1 outcome; null if verify never ran
  workflow: z.object({
    id: idSchema('workflow'),
    version: z.number().int().positive(),
    contentHash: sha256Schema,
  }),
  steps: z.array(
    z.object({
      stepKey: stepKeySchema,
      revisionIndex: z.number().int().nonnegative(),
      retryIndex: z.number().int().nonnegative(),
      state: stepStateSchema,
      profileName: z.string().nullable(),
      providerId: providerIdSchema.nullable(),
      modelId: z.string().nullable(),
      cost: z.object({
        settledMicrousd: microusdSchema,
        certainty: costCertaintySchema, // weakest certainty among the step's settled attempts
        unknownMicrousd: microusdSchema,
      }),
    }),
  ),
  totals: reportTotalsSchema,
  /**
   * Legacy: unknown charges still open when the report was generated. Optional and always empty for runs reported
   * since decision 1 (an uncertain outcome is settled as an estimate, listed in `estimatedCharges`).
   */
  unknownLiabilities: z
    .array(
      z.object({
        attemptId: idSchema('attempt'),
        stepKey: stepKeySchema,
        liabilityMicrousd: microusdSchema,
        state: z.enum(['unknown', 'abandoned']),
      }),
    )
    .optional(),
  /**
   * Decision 1: attempts whose outcome was uncertain, settled as estimates (still estimated when the report was
   * generated). `mayNotHaveBeenCharged`: the request may never have reached the provider. Optional (additive).
   */
  estimatedCharges: z
    .array(
      z.object({
        attemptId: idSchema('attempt'),
        stepKey: stepKeySchema,
        amountMicrousd: microusdSchema,
        mayNotHaveBeenCharged: z.boolean(),
      }),
    )
    .optional(),
  artifacts: z.object({
    findings: idSchema('artifact').nullable(),
    plan: idSchema('artifact').nullable(),
    patch: idSchema('artifact').nullable(),
    review: idSchema('artifact').nullable(),
  }),
  limitations: z.array(z.string().max(600)), // honesty text (07 constants)
  snapshotUsed: z.boolean(), // true when use_preserved_snapshot skipped the stale check
  generatedAt: epochMsSchema,
  /**
   * Every approval the run opened, oldest first: the user's decision (null = never decided) and, when it stopped
   * binding, why (06 F17). Optional (additive): reports generated before wave 4 do not carry it.
   */
  approvals: z
    .array(
      z.object({
        approvalId: idSchema('approval'),
        stepKey: stepKeySchema,
        planArtifactId: idSchema('artifact'),
        planHash: sha256Schema,
        decision: approvalDecisionSchema.nullable(),
        decidedAt: epochMsSchema.nullable(),
        note: z.string().max(2_000).nullable(),
        invalidatedReason: z.enum(APPROVAL_STALE_REASONS).nullable(),
        createdAt: epochMsSchema,
      }),
    )
    .optional(),
  /**
   * Quality revision cycles (§12.4 revisionPolicy) under the current approval vs the run limit, how many times the
   * plan was re-done (request_revision / replan), and why the run ended `incomplete` (null otherwise). Optional (additive).
   */
  revisions: z
    .object({
      cycles: z.number().int().nonnegative(),
      maxCycles: z.number().int().nonnegative(),
      planRevisions: z.number().int().nonnegative(),
      incompleteCause: z.enum(['revision_limit', 'verifier_incomplete']).nullable(),
    })
    .optional(),
  /**
   * Per step key (E1): the display name from the workflow spec and, for a model step, the instruction version whose
   * text the run used (e.g. "reviewer.v2": an edited prompt gets a new version name, the old text stays with the runs
   * that used it). Optional (additive): earlier reports do not carry it.
   */
  stepMeta: z
    .array(z.object({ stepKey: stepKeySchema, name: z.string().max(60).nullable(), instructionVersion: z.string().nullable() }))
    .optional(),
});
/** `report.v1` value. */
export type ReportV1 = z.infer<typeof reportV1Schema>;
