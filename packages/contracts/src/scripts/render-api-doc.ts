import { z } from 'zod';
import type { AnyOperationDef, RateLimit } from '../ipc/common.js';
import { UNIVERSAL_ERROR_CODES } from '../ipc/common.js';

function formatRate(r: RateLimit | undefined): string {
  if (r === undefined) return 'default';
  return `${String(r.capacity)} / refill ${String(Number(r.refillPerSec.toFixed(4)))} per s`;
}

function schemaJson(schema: z.ZodType): string {
  // io 'input' documents what callers send; outputs use the same mode because branded ids are transforms.
  return JSON.stringify(z.toJSONSchema(schema, { io: 'input', unrepresentable: 'any' }), null, 2);
}

function shortChannel(channel: string): string {
  return channel.replace(/^relay\/v1\//, '');
}

/**
 * Renders the IPC API reference (02 §B0 "Docs") for the given operations as markdown.
 * Pure: the caller decides where the text goes. Documents renderer-exposed `OPERATIONS` only.
 */
export function renderApiDoc(ops: readonly AnyOperationDef[]): string {
  // The operation table comes first so `gen:api-doc | head -5` shows it even below pnpm's script banner.
  const lines: string[] = [
    '| Channel | Kind | Route | Idempotency key | Errors | Rate limit |',
    '|---|---|---|---|---|---|',
  ];
  for (const d of ops) {
    const errs = d.errors.length === 0 ? '—' : d.errors.map((e) => `\`${e}\``).join(', ');
    lines.push(
      `| \`${d.channel}\` | ${d.kind} | ${d.route} | ${d.idempotent ? 'required' : '—'} | ${errs} | ${formatRate(d.rateLimit)} |`,
    );
  }
  lines.push(
    '',
    '# Relay IPC API (v1)',
    '',
    '> Generated by `pnpm gen:api-doc` from `@relay/contracts` `OPERATIONS`. Do not edit by hand.',
    '',
    `Every operation may also return ${UNIVERSAL_ERROR_CODES.map((c) => `\`${c}\``).join(', ')}.`,
    'Results use the envelope `{ ok: true, data, meta? } | { ok: false, error: AppError }`.',
    '',
  );
  for (const d of ops) {
    lines.push(
      `## \`${shortChannel(d.channel)}\``,
      '',
      `Channel \`${d.channel}\` · ${d.kind} · route \`${d.route}\``,
      '',
      '### Input',
      '',
      '```json',
      schemaJson(d.input),
      '```',
      '',
      '### Output',
      '',
      '```json',
      schemaJson(d.output),
      '```',
      '',
    );
  }
  return lines.join('\n');
}
